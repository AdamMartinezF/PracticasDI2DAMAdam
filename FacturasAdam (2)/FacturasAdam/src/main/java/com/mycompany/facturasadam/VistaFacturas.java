    // Estos metodos sirven para mostrar cambios en pantalla
    public void cargarFactura(Factura f) {
        jTextField1.setText(f.getAsunto());
        jTextField2.setText(String.valueOf(f.getCantidad()));
        Empresas.setSelectedItem(f.getTipo());

        jSpinner5.setValue(f.getFecha().getDayOfMonth());
        jSpinner2.setValue(f.getFecha().getMonthValue());
        jSpinner4.setValue(f.getFecha().getYear());
    }

    public void limpiarSeleccion() {
        jList1.clearSelection();
    }

    public void refrescarLista(List<Factura> facturas) {
        listModel.clear();
        for (Factura f : facturas) {
            listModel.addElement(f.toString());
        }
    }

    public void mostrarError(String mensaje) {
        jLabel6.setForeground(Color.RED);
        jLabel6.setText(mensaje);
    }

    public void mostrarExito(String mensaje) {
        jLabel6.setForeground(new Color(0, 128, 0));
        jLabel6.setText(mensaje);
    }

